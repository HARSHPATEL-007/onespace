  async getUpstream(resourceId: string, depth=5){
    await this.assert("READ");
    const visited = new Set<string>(); const queue: Array<{id:string;depth:number}> = [{id: resourceId,depth:0}]; const result: unknown[] = [];
    // BFS upstream via parentIds
    while(queue.length){
      const cur = queue.shift()!;
      if(cur.depth>depth || visited.has(cur.id)) continue; visited.add(cur.id);
      const rec = await safe(()=>(prisma as never as { healthProvenanceRecord:{findFirst:(a:unknown)=>Promise<{id:string;targetResourceId:string;entityType:string;activityType:string;agentType:string;parentIds:string[]}|null>}}).healthProvenanceRecord.findFirst({ where:{workspaceId:this.workspaceId, targetResourceId: cur.id}}), null) ?? await safe(()=>(prisma as never as { healthProvenanceRecord:{findFirst:(a:unknown)=>Promise<unknown>}}).healthProvenanceRecord.findFirst({ where:{id: cur.id, workspaceId:this.workspaceId}}), null) as unknown as {id:string;parentIds:string[]}|null;
      if(rec){ result.push(rec); for(const pid of (rec as {parentIds:string[]}).parentIds ?? []) queue.push({id: pid, depth: cur.depth+1}); }
    }
    return result;
  }
  async getDownstream(resourceId: string, depth=5){
    await this.assert("READ");
    // Find record for resourceId, then BFS via childIds
    const start = await safe(()=>(prisma as never as { healthProvenanceRecord:{findFirst:(a:unknown)=>Promise<{id:string;childIds:string[]}|null>}}).healthProvenanceRecord.findFirst({ where:{workspaceId:this.workspaceId, targetResourceId: resourceId}}), null);
    if(!start) return [];
    const visited = new Set<string>(); const queue: Array<{id:string;depth:number}> = [{id: (start as {id:string}).id,depth:0}]; const result: unknown[] = [];
    while(queue.length){
      const cur = queue.shift()!;
      if(cur.depth>depth || visited.has(cur.id)) continue; visited.add(cur.id);
      const rec = await safe(()=>(prisma as never as { healthProvenanceRecord:{findFirst:(a:unknown)=>Promise<{id:string;childIds:string[]}|null>}}).healthProvenanceRecord.findFirst({ where:{id: cur.id, workspaceId:this.workspaceId}}), null);
      if(rec){ result.push(rec); for(const cid of (rec as {childIds:string[]}).childIds ?? []) queue.push({id: cid, depth: cur.depth+1}); }
    }
    return result;
  }
