  // ── Time integrity — 8 timestamps + clock offset ───────────────────────
  static timeIntegrity(timing: { event_time?: string; device_time?: string; ingestion_time?: string; }){
    const now = new Date().toISOString();
    const event = timing.event_time ?? now;
    const device = timing.device_time ?? event;
    const ingestion = timing.ingestion_time ?? now;
    const offset = new Date(event).getTime() - new Date(device).getTime();
    const sync = Math.abs(offset) < 5000 ? "within_tolerance" : "temporally_uncertain";
    return { event_time: event, device_time: device, ingestion_time: ingestion, processing_time: now, clock_offset_ms: offset, synchronization: sync, time_source: "NTP_authenticated" };
  }

