  // ── Event-sourcing — append-only, reconstruct any point in time ───────
  private async appendEvent(input: { aggregateId: string; eventType: string; patientId: string|null; payload: Record<string,unknown>; parentEventId?: string|null; }){
    const last = await safe(()=>(prisma as never as { healthProvenanceEvent:{findFirst:(a:unknown)=>Promise<{currentPayloadHash:string|null}|null>}}).healthProvenanceEvent.findFirst({ where:{workspaceId:this.workspaceId, aggregateId: input.aggregateId}, orderBy:{timestamp:"desc"}}), null);
    const previousStateHash = (last as {currentPayloadHash:string|null}|null)?.currentPayloadHash ?? null;
    const currentPayloadHash = sha256(JSON.stringify(input.payload));
    await safe(()=>(prisma as never as { healthProvenanceEvent:{create:(a:unknown)=>Promise<unknown>}}).healthProvenanceEvent.create({ data:{
      workspaceId:this.workspaceId, patientId: input.patientId, eventId: `event-${crypto.randomUUID().slice(0,8)}`, eventType: input.eventType as never, aggregateId: input.aggregateId,
      actor: this.userId, timestamp: new Date(), previousStateHash, currentPayloadHash, parentEventId: input.parentEventId ?? null,
      softwareVersion:"vitality-Ω", policyVersion:"wallet-policy-4.2", signature:{ class:"SYSTEM", algorithm:"sha256", key_id:"n0va-provenance-key", hash: currentPayloadHash } as never,
      retentionClass:"P2" as never, payload: input.payload as never,
    } as never}), null);
  }
