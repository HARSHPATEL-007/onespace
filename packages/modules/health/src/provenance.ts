  // ── Observation trust — Level 1-3 + FHIR Observation + FHIR Provenance ──
  async createObservationTrust(input: z.infer<typeof observationTrustSchema>){
    await this.assert("CREATE");
    const observationId = `obs-${crypto.randomUUID().slice(0,8)}`;
    const contentHash = sha256(JSON.stringify(input.value));
    // Time integrity — preserve 8 timestamps
    const now = new Date();
    const timing = { event_time: (input.timing as Record<string,unknown>)?.event_time ?? now.toISOString(), device_time: (input.timing as Record<string,unknown>)?.device_time ?? now.toISOString(), ingestion_time: now.toISOString(), processing_time: now.toISOString(), clock_offset_ms: (input.timing as Record<string,unknown>)?.clock_offset_ms ?? 0, synchronization: (input.timing as Record<string,unknown>)?.synchronization ?? "within_tolerance", time_source: "NTP_authenticated", ...(input.timing as Record<string,unknown> ?? {}) };
    if (timing.synchronization !== "within_tolerance") input.trustLabel = "UNVERIFIED" as never;
    // Signal-quality envelope — prevent high-risk inference when below threshold
    const qualityScore = (input.quality as Record<string,unknown>)?.score as number | undefined ?? (input.quality as Record<string,unknown>)?.overall as number | undefined ?? 1;
    const qualityStatus = qualityScore >= 0.85 ? "high_quality" : qualityScore >= 0.6 ? "usable_with_caution" : qualityScore >= 0.3 ? "poor_quality" : "uninterpretable";
    if (qualityStatus === "poor_quality" || qualityStatus === "uninterpretable") input.trustLabel = "UNVERIFIED" as never;
    const fhirObservation = { resourceType:"Observation", id: observationId, status:"final", code:{ coding:[{ code: input.code }] }, subject:{ reference:`Patient/${input.patientId}` }, encounter: input.encounterId? { reference:`Encounter/${input.encounterId}` }: undefined, valueQuantity:{ value: (input.value as {amount:number; unit:string}).amount, unit: (input.value as {amount:number; unit:string}).unit }, extension:[{ url:"http://n0va.health/fhir/StructureDefinition/observation-trust-label", valueString: input.trustLabel }, { url:"http://n0va.health/fhir/StructureDefinition/observation-quality", valueDecimal: qualityScore }] };
    const fhirProvenance = { resourceType:"Provenance", target:[{ reference:`Observation/${observationId}` }], recorded: now.toISOString(), agent:[{ who:{ reference:`Device/${(input.source as Record<string,unknown>)?.device_id ?? "unknown"}` }, role:{ coding:[{ code: input.origin.toLowerCase() }] } }], entity:[{ role:"source", what:{ reference:`Device/${(input.source as Record<string,unknown>)?.device_id ?? "unknown"}` }}], extension:[{ url:"http://n0va.health/fhir/StructureDefinition/provenance-signal-quality", valueDecimal: qualityScore }] };
    const row = await (prisma as never as { healthObservationTrust:{create:(a:unknown)=>Promise<unknown>}}).healthObservationTrust.create({ data:{
      workspaceId:this.workspaceId, patientId: input.patientId, encounterId: input.encounterId ?? null, observationId, code: input.code, value: input.value as never, origin: input.origin as never,
      source: (input.source ?? {}) as never, timing: timing as never, quality: { score: qualityScore, status: qualityStatus, ...(input.quality as Record<string,unknown> ?? {}) } as never, calibration: (input.calibration ?? {}) as never, transformation: (input.transformation ?? {}) as never,
      provenanceRef: `prov-${observationId}`, contentHash, trustLabel: input.trustLabel as never, retentionClass: input.retentionClass as never, fhirObservation: fhirObservation as never, fhirProvenanceId: `prov-${observationId}`,
    } as never });
    // Provenance graph — W3C PROV Entities/Activities/Agents
    await this.createProvenanceRecord({ targetResourceType:"Observation", targetResourceId: observationId, entityType:"observation", activityType:"capture", agentType:"device", agentId: (input.source as Record<string,unknown>)?.device_id as string | undefined, origin: input.origin, trustLabel: input.trustLabel, fhirProvenance });
    await this.appendEvent({ aggregateId: observationId, eventType:"OBSERVATION_RECEIVED", patientId: input.patientId, payload:{ observationId, value: input.value, quality: qualityScore, fhirObservation }});
    await this.audit("CREATE","HealthObservationTrust",observationId, input as never);
    return row;
  }
